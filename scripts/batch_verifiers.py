#!/usr/bin/env python3
"""Derive internal verifier libraries from the pinned circuit exports."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
for name in ('Verifier', 'NativeVerifier'):
    source = (root / 'src' / f'{name}.sol').read_text()
    source = re.sub(r'//[^\n]*', '', source)
    source = source.replace(f'contract {name}', f'library Batch{name}')
    source = re.sub(r'\bpublic\b', 'internal', source)
    source = re.sub(r'\n\s*\n', '\n\n', source).lstrip()
    (root / 'src' / f'Batch{name}.sol').write_text(
        '// SPDX-License-Identifier: MIT\n'
        '// Generated by scripts/batch_verifiers.py from the pinned verifier.\n' + source
    )
